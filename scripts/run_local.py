def fmt(v, pct=False, money=False):
    if v is None:
        return "N/A"
    if pct:
        return f"{v * 100:.1f}%"
    if money:
        return f"${v:,.2f}" if abs(v) < 100 else f"${v:,.0f}"
    if isinstance(v, float):
        return f"{v:,.2f}"
    if isinstance(v, int) and not isinstance(v, bool):
        return f"{v:,}"
    return str(v)


def table(rows, cols):
    head = "| " + " | ".join(h for h, *_ in cols) + " |\n|" + "---|" * len(cols) + "\n"
    body = ""
    for r in rows:
        body += "| " + " | ".join(fmt(r[k], **(o[0] if o else {})) for _, k, *o in cols) + " |\n"
    return head + body


def write_csvs(out):
    for layer in ("silver", "gold"):
        d = ROOT / "out" / layer
        d.mkdir(parents=True, exist_ok=True)
        for name, rows in out[layer].items():
            if rows:
                cols = list(dict.fromkeys(k for r in rows for k in r))
                with open(d / f"{name}.csv", "w", newline="") as fh:
                    w = csv.DictWriter(fh, fieldnames=cols)
                    w.writeheader()
                    w.writerows(rows)



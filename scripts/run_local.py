def main():
    out = run_local()
    write_csvs(out)
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "results.md").write_text(results_md(out))
    for r in out["gold"]["gold_scenario_summary"]:
        print(f"{r['scenario_id']:<30} ready {r['bags_ready_on_time']:>7,} / {r['bags_ordered']:,}  "
              f"cost ${r['incremental_cost_usd']:>9,.2f}  constraint {r['primary_constraint']}")
    bad = [c for c in out["silver_checks"] + out["gold"]["gold_validation_results"] if c["status"] != "PASS"]
    print(f"checks failed: {len(bad)}")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
